# Expected values for a qwen-gdn check build (GDN_CHECK >= 1).
#
#   python3 gen_check.py <B> <out.h>
#
# The pattern (main.c, "Pattern") keeps every fp16 operation exact, so an integer model in units
# of 1/256 is the reference. Per chunk and row this writes c (= beta (v - alpha pred), x256) and
# the expected o bits; the device checks o, and the state at the columns where k != 0 (plus
# column 0) from c -- cheap enough for RTL. GDN_CHECK=2 also checks every state element.
import sys

KH, VPK, D, RC = 16, 3, 128, 32
RB = D // RC
CPS = KH * VPK * RB


def ident(c):
    rb = c % RB
    vs = (c // RB) % VPK
    kh = (c // (RB * VPK)) % KH
    b = c // CPS
    return b, kh, kh * VPK + vs, rb


def s0(i, j):
    return (2 * i + 3 * j) % 5 - 2


def kpat(b, kh, j):
    m = (j + 3 * kh + b) % 16
    return 1 if m == 0 else (-1 if m == 8 else 0)


def qpat(b, kh, j):
    m = (j + 5 * kh + 2 * b) % 16
    return 1 if m == 3 else (-1 if m == 11 else 0)


def f16_of_fix256(v):
    """v / 256 as fp16 bits; must be exact."""
    if v == 0:
        return 0
    s = 0x8000 if v < 0 else 0
    a, e = abs(v), 7
    while a >= 2048:
        assert a & 1 == 0, "pattern value not exact in fp16"
        a >>= 1
        e += 1
    while a < 1024:
        a <<= 1
        e -= 1
    return s | ((e + 10) << 10) | (a & 0x3FF)


def main():
    B, out = int(sys.argv[1]), sys.argv[2]
    nc = CPS * B
    cs, os_ = [], []
    for c in range(nc):
        b, kh, vh, rb = ident(c)
        a256 = 64 if vh % 2 else 128
        b256 = 128 if (vh // 2) % 2 else 64
        k = [kpat(b, kh, j) for j in range(D)]
        q = [qpat(b, kh, j) for j in range(D)]
        for i in range(RC):
            v = ((rb * RC + i) * 3 + vh + b) % 7 - 3
            pred = sum(s0(i, j) * k[j] for j in range(D))
            x = 256 * v - a256 * pred
            assert (b256 * x) % 256 == 0
            c256 = b256 * x // 256
            o256 = sum(q[j] * (a256 * s0(i, j) + c256 * k[j]) for j in range(D))
            cs.append(c256)
            os_.append(f16_of_fix256(o256))
    with open(out, "w") as f:
        f.write("// GENERATED by qwen-gdn/script/gen_check.py -- do not hand-edit.\n")
        f.write(f"#ifndef GDN_CHECK_H\n#define GDN_CHECK_H\n#define GDN_CHECK_B {B}\n")
        f.write(f"static const int16_t gdn_c256[{len(cs)}] = {{{','.join(map(str, cs))}}};\n")
        f.write(f"static const uint16_t gdn_o_bits[{len(os_)}] = {{"
                + ",".join(f"0x{v:04x}" for v in os_) + "};\n#endif\n")
    print(f"wrote {out}: B={B}, {nc} chunks")


if __name__ == "__main__":
    main()
