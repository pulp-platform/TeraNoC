// qwen-ffn: choose the K tile and strip width of BOTH phases under one L1 budget.
//
//   gen_joint <gu_cands> <dn_cands> <gu_tiles.h> <dn_tiles.h> <joint.h>
//
// Each candidate file starts with "L1 <l1_bytes> <stack_bytes>" (gen_cands.c).
//
// The phases are sequential, so each phase's own buffers (its A operand, C strip, K-split
// partials -- gen_cands.c "own") all coexist, but there is ONE W double buffer: two regions of
// the larger slot, which the stream hands from gate+up to down without a gap. A pair fits when
//     own_gu + own_dn + 2 * max(wslot_gu, wslot_dn) + stacks <= L1.
// Among the pairs that fit, take the one with the most log2(kt) + log2(pt) over both phases (the
// same tallest-tile / widest-strip preference each stand-alone app has), ties to the taller
// down tile.
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

typedef struct { unsigned kt, pt, ldp; unsigned long long wslot, own; } cand_t;

static unsigned long long g_l1, g_stacks;
static int load(const char *path, cand_t *c, int max) {
  FILE *f = fopen(path, "r");
  if (!f) { perror(path); exit(1); }
  if (fscanf(f, "L1 %llu %llu", &g_l1, &g_stacks) != 2) {
    fprintf(stderr, "%s: no L1 line\n", path);
    exit(1);
  }
  int n = 0;
  while (n < max && fscanf(f, "%u %u %llu %llu %u", &c[n].kt, &c[n].pt, &c[n].wslot, &c[n].own,
                           &c[n].ldp) == 5)
    ++n;
  fclose(f);
  return n;
}

static void emit_tiles(const char *path, const cand_t *c, const char *phase,
                       unsigned long long total, unsigned long long l1) {
  FILE *f = fopen(path, "w");
  if (!f) { perror(path); exit(1); }
  fprintf(f, "// GENERATED by qwen-ffn/script/gen_joint.c -- do not hand-edit.\n");
  fprintf(f, "#ifndef QWEN_TILES_H\n#define QWEN_TILES_H\n");
  fprintf(f, "// %s: chosen jointly with the other phase; L1 %.1f of %.1f MiB in all.\n", phase,
          total / 1048576.0, l1 / 1048576.0);
  fprintf(f, "#define QWEN_KT %u\n#define QWEN_PT %u\n#endif\n", c->kt, c->pt);
  fclose(f);
}

int main(int argc, char **argv) {
  if (argc != 6) {
    fprintf(stderr, "usage: %s gu_cands dn_cands gu.h dn.h joint.h\n", argv[0]);
    return 2;
  }
  static cand_t gu[1024], dn[1024];
  const int ngu = load(argv[1], gu, 1024), ndn = load(argv[2], dn, 1024);
  const unsigned long long l1 = g_l1, stacks = g_stacks;
  int bg = -1, bd = -1;
  double best = -1.0;
  unsigned long long best_total = 0;
  for (int i = 0; i < ngu; ++i)
    for (int j = 0; j < ndn; ++j) {
      const unsigned long long w = gu[i].wslot > dn[j].wslot ? gu[i].wslot : dn[j].wslot;
      const unsigned long long total = gu[i].own + dn[j].own + 2 * w + stacks;
      if (total >= l1) continue;
      const double score = log2(gu[i].kt) + log2(gu[i].pt) + log2(dn[j].kt) + log2(dn[j].pt) +
                           1e-3 * log2(dn[j].kt);
      if (score > best) { best = score; bg = i; bd = j; best_total = total; }
    }
  if (bg < 0) {
    fprintf(stderr, "gen_joint: no (gate+up, down) tiling fits %.1f MiB of L1 -- lower the batch\n",
            l1 / 1048576.0);
    return 1;
  }
  emit_tiles(argv[3], &gu[bg], "gate+up", best_total, l1);
  emit_tiles(argv[4], &dn[bd], "down", best_total, l1);
  FILE *f = fopen(argv[5], "w");
  if (!f) { perror(argv[5]); return 1; }
  const unsigned long long w = gu[bg].wslot > dn[bd].wslot ? gu[bg].wslot : dn[bd].wslot;
  fprintf(f, "// GENERATED by qwen-ffn/script/gen_joint.c -- do not hand-edit.\n");
  fprintf(f, "#ifndef FFN_JOINT_H\n#define FFN_JOINT_H\n");
  fprintf(f, "// gate+up KT=%u PT=%u (slot %llu B), down KT=%u PT=%u (slot %llu B)\n", gu[bg].kt,
          gu[bg].pt, gu[bg].wslot, dn[bd].kt, dn[bd].pt, dn[bd].wslot);
  fprintf(f, "// L1: gate+up own %llu + down own %llu + W 2 x %llu + stacks %llu = %llu of %llu B\n",
          gu[bg].own, dn[bd].own, w, stacks, best_total, l1);
  fprintf(f, "#define FFN_WREG_ELEMS %lluu  // one W region (elements): the larger slot\n", w / 2);
  fprintf(f, "#define FFN_J_GU_KT %uu\n#define FFN_J_GU_PT %uu\n", gu[bg].kt, gu[bg].pt);
  fprintf(f, "#define FFN_J_DN_KT %uu\n#define FFN_J_DN_PT %uu\n", dn[bd].kt, dn[bd].pt);
  fprintf(f, "#endif\n");
  fclose(f);
  return 0;
}
