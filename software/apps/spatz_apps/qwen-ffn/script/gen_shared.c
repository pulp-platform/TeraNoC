// qwen-ffn: what the gate+up phase must know about the down phase, written as a header the
// gate+up translation unit includes. Compiled with the DOWN phase's shape and tiles on the
// include path, so the H layout (down's A operand) and its multi-hot check pattern come from the
// very macros the down phase uses.
#include <stdint.h>
#include <stdio.h>

#include "qwen_layout.h"

int main(void) {
  printf("// GENERATED by qwen-ffn/script/gen_shared.c (down phase layout) -- do not hand-edit.\n");
  printf("#ifndef FFN_SHARED_H\n#define FFN_SHARED_H\n");
  printf("// H = SiLU(G) * U is down's A operand: [B][FFN_H_LDX], FFN_H_REPLICAS copies.\n");
  printf("#define FFN_H_LDX %uu\n", (unsigned)QWEN_LDX);
  printf("#define FFN_H_REPLICAS %uu\n", (unsigned)QWEN_X_REPLICAS);
  printf("#define FFN_H_STRIDE_E %uu\n", (unsigned)QWEN_X_STRIDE_E);
  printf("#define FFN_H_ELEMS %uu\n", (unsigned)QWEN_X_ELEMS);
  printf("// Down's K tiling, for the check pattern (qwen_pattern.h) that lights H.\n");
  printf("#define FFN_DN_K %uu\n", (unsigned)QWEN_K);
  printf("#define FFN_DN_KT %uu\n", (unsigned)QWEN_KT);
  printf("#define FFN_DN_KT_CORE %uu\n", (unsigned)QWEN_KT_CORE);
  printf("#define FFN_DN_KSPLIT %uu\n", (unsigned)QWEN_KSPLIT);
  printf("#define FFN_DN_SEQ_TOTAL %uu  // W tiles the down phase streams\n",
         (unsigned)(QWEN_NSTRIPS * QWEN_STAGES_N * (QWEN_K / QWEN_KT)));
  printf("#endif\n");
  return 0;
}
