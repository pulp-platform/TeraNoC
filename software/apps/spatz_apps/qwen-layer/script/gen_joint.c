// qwen-layer: choose the K tile and strip width of every projection phase (qkvz, o-proj and,
// for the full layer, gate+up and down) under one L1 budget that also holds the mixer
// (qwen-ffn/script/gen_joint.c generalised to N phases, plus the mixer's reserve).
//
//   gen_joint <joint.h> <reserve> <state> <name> <cands> <tiles.h> [<name> <cands> <tiles.h> ...]
//
// Each candidate file starts with "L1 <l1_bytes> <stack_bytes>" (qwen-ffn/script/gen_cands.c),
// then "kt pt wslot own ldp" per line. The phases run one after the other, so their own buffers
// (A operand, C strip, K-split partials) all coexist, but there is ONE W double buffer: two
// regions of the largest slot, handed from phase to phase. reserve: the mixer's L1 apart from its
// state tiles; state: those tiles, which share the W area when it is at least that big (it is
// idle during the mixer), else come on top. A combination fits when
//     sum(own) + 2 * max(wslot) + stacks + reserve + (state > 2 * max(wslot) ? state : 0) <= L1.
// Among those, the most sum(log2 kt + log2 pt) wins (each stand-alone app's tallest-tile /
// widest-strip preference).
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

#define MAXP 4
#define MAXC 512

typedef struct { unsigned kt, pt, ldp; unsigned long long wslot, own; } cand_t;

static unsigned long long g_l1, g_stacks;
static int load(const char *path, cand_t *c) {
  FILE *f = fopen(path, "r");
  if (!f) { perror(path); exit(1); }
  if (fscanf(f, "L1 %llu %llu", &g_l1, &g_stacks) != 2) {
    fprintf(stderr, "%s: no L1 line\n", path);
    exit(1);
  }
  int n = 0;
  while (n < MAXC && fscanf(f, "%u %u %llu %llu %u", &c[n].kt, &c[n].pt, &c[n].wslot, &c[n].own,
                            &c[n].ldp) == 5)
    ++n;
  fclose(f);
  return n;
}

static int np;
static const char *name[MAXP], *tiles[MAXP];
static cand_t cand[MAXP][MAXC];
static int ncand[MAXP], pick[MAXP], best_pick[MAXP];
static unsigned long long reserve, state, best_total;
static double best = -1.0;

static void search(int p, unsigned long long own, unsigned long long w, double score) {
  if (p == np) {
    const unsigned long long total = own + 2 * w + g_stacks + reserve + (state > 2 * w ? state : 0);
    if (total < g_l1 && score > best) {
      best = score;
      best_total = total;
      for (int i = 0; i < np; ++i) best_pick[i] = pick[i];
    }
    return;
  }
  for (int i = 0; i < ncand[p]; ++i) {
    pick[p] = i;
    const cand_t *c = &cand[p][i];
    search(p + 1, own + c->own, c->wslot > w ? c->wslot : w,
           score + log2(c->kt) + log2(c->pt) + 1e-3 * log2(c->kt));
  }
}

int main(int argc, char **argv) {
  if (argc < 7 || (argc - 4) % 3 != 0 || (argc - 4) / 3 > MAXP) {
    fprintf(stderr, "usage: %s joint.h reserve state name cands tiles.h [...]\n", argv[0]);
    return 2;
  }
  reserve = strtoull(argv[2], 0, 10);
  state = strtoull(argv[3], 0, 10);
  np = (argc - 4) / 3;
  for (int p = 0; p < np; ++p) {
    name[p] = argv[4 + 3 * p];
    ncand[p] = load(argv[5 + 3 * p], cand[p]);
    tiles[p] = argv[6 + 3 * p];
  }
  search(0, 0, 0, 0.0);
  if (best < 0) {
    fprintf(stderr, "gen_joint: no tiling of the %d phases fits %.1f MiB of L1 with the mixer -- "
            "lower the batch\n", np, g_l1 / 1048576.0);
    return 1;
  }
  unsigned long long w = 0;
  for (int p = 0; p < np; ++p) {
    const cand_t *c = &cand[p][best_pick[p]];
    if (c->wslot > w) w = c->wslot;
    FILE *f = fopen(tiles[p], "w");
    if (!f) { perror(tiles[p]); return 1; }
    fprintf(f, "// GENERATED by qwen-layer/script/gen_joint.c -- do not hand-edit.\n");
    fprintf(f, "#ifndef QWEN_TILES_H\n#define QWEN_TILES_H\n");
    fprintf(f, "// %s: chosen jointly with the other phases; L1 %.1f of %.1f MiB in all.\n", name[p],
            best_total / 1048576.0, g_l1 / 1048576.0);
    fprintf(f, "#define QWEN_KT %u\n#define QWEN_PT %u\n#endif\n", c->kt, c->pt);
    fclose(f);
  }
  FILE *f = fopen(argv[1], "w");
  if (!f) { perror(argv[1]); return 1; }
  fprintf(f, "// GENERATED by qwen-layer/script/gen_joint.c -- do not hand-edit.\n");
  fprintf(f, "#ifndef QL_JOINT_H\n#define QL_JOINT_H\n");
  unsigned long long own = 0;
  for (int p = 0; p < np; ++p) {
    const cand_t *c = &cand[p][best_pick[p]];
    own += c->own;
    fprintf(f, "// %s KT=%u PT=%u (slot %llu B, own %llu B)\n", name[p], c->kt, c->pt, c->wslot,
            c->own);
  }
  fprintf(f, "// L1: own %llu + W 2 x %llu + stacks %llu + mixer %llu%s = %llu of %llu B\n", own, w,
          g_stacks, reserve, state > 2 * w ? " + state" : "", best_total, g_l1);
  fprintf(f, "#define QL_WREG_ELEMS %lluu  // one W region (elements): the largest slot\n", w / 2);
  fprintf(f, "#define QL_STATE_IN_W %d  // the mixer's state tiles (%llu B) in the W area\n",
          state <= 2 * w, state);
  fprintf(f, "#endif\n");
  fclose(f);
  return 0;
}
