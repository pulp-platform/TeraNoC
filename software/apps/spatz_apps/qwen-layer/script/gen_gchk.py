# Reference for the GDN mixer value self-test (qwen-layer ql_gchk=1, mixer_gdn.c "self-test").
#
#   python3 gen_gchk.py <B> <T> <out.h>
#
# The device fills the state, q, k, v, z and x with the patterns below (all exact in fp16), runs
# the mixer for TWO decode steps (aux refilled in between; the state carries over) and compares
# the second step's o' with this float64 model of the per-token recurrence:
#   alpha = exp(-softplus(a)), beta = sigmoid(b), a = b = x_row . w_ab (w_ab = 2^-10 everywhere)
#   k^ = k / |k|, q^ = q / |q| / sqrt(128)
#   pred = S k^ ; c = beta (v - alpha pred) ; S <- alpha S + c k^T ; o = S q^
#   o' = o * rsqrt(mean_head(o^2) + 1e-6) * SiLU(z)
import sys

import numpy as np

KH, VPK, D, RC = 16, 3, 128, 32
VH = KH * VPK
H = 4096


def s0(b, vh, i, g):
    return ((2 * i + 3 * g + vh + 5 * b) % 9 - 4) / 16.0


def kpat(b, kh, j, d):
    return ((7 * d + 3 * kh + 5 * j + b) % 17 - 8) / 8.0


def qpat(b, kh, j, d):
    return ((5 * d + 7 * kh + 3 * j + 2 * b) % 15 - 7) / 8.0


def vpat(b, vh, j, i):
    return ((5 * i + vh + 3 * j + 7 * b) % 13 - 6) / 8.0


def zpat(b, vh, j, i):
    return ((3 * i + 2 * vh + j + b) % 11 - 5) / 4.0


def xval(j):
    return (j - 1) / 8.0


def f16_bits(v):
    return int(np.array([v], dtype=np.float16).view(np.uint16)[0])


def main():
    B, T, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
    i_ = np.arange(D)[:, None]
    g_ = np.arange(D)[None, :]
    ref = np.zeros((B * T, VH * D))
    for b in range(B):
        for vh in range(VH):
            kh = vh // VPK
            S = ((2 * i_ + 3 * g_ + vh + 5 * b) % 9 - 4) / 16.0
            for step in range(2):
                for j in range(T):
                    a = H * xval(j) * 2.0 ** -10
                    alpha = np.exp(-np.logaddexp(0.0, a))
                    beta = 1.0 / (1.0 + np.exp(-a))
                    d = np.arange(D)
                    k = ((7 * d + 3 * kh + 5 * j + b) % 17 - 8) / 8.0
                    q = ((5 * d + 7 * kh + 3 * j + 2 * b) % 15 - 7) / 8.0
                    k = k / np.sqrt(k @ k + 1e-6)
                    q = q / np.sqrt(q @ q + 1e-6) / np.sqrt(128.0)
                    v = ((5 * d + vh + 3 * j + 7 * b) % 13 - 6) / 8.0
                    c = beta * (v - alpha * (S @ k))
                    S = alpha * S + np.outer(c, k)
                    if step == 1:
                        o = S @ q
                        z = ((3 * d + 2 * vh + j + b) % 11 - 5) / 4.0
                        r = 1.0 / np.sqrt(np.mean(o * o) + 1e-6)
                        ref[b * T + j, vh * D:(vh + 1) * D] = o * r * z / (1.0 + np.exp(-z))
    with open(out, 'w') as f:
        f.write('// GENERATED by qwen-layer/script/gen_gchk.py %d %d -- do not hand-edit.\n' % (B, T))
        f.write('#define QL_GCHK_B %du\n#define QL_GCHK_T %du\n' % (B, T))
        f.write('static const uint16_t ql_gchk_ref[%d] __attribute__((section(".l2"), aligned(4096))) = {\n' %
                ref.size)
        flat = [f16_bits(x) for x in ref.ravel()]
        for n in range(0, len(flat), 16):
            f.write('  ' + ', '.join('0x%04x' % x for x in flat[n:n + 16]) + ',\n')
        f.write('};\n')


if __name__ == '__main__':
    main()
