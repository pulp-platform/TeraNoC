// qwen-layer: one phase's A operand layout (qwen_layout.h QWEN_X_*), as macros other
// translation units can use. Compiled with that phase's data/ (shape + tiles) on the path.
//   gen_a <PREFIX>   e.g. QL_X (qz's A = x) or QL_O (op's A = o')
#include <stdio.h>

#include "qwen_layout.h"

int main(int argc, char **argv) {
  if (argc != 2) return 2;
  const char *p = argv[1];
  printf("// GENERATED by qwen-layer/script/gen_a.c -- do not hand-edit.\n");
  printf("#ifndef %s_LAYOUT_H\n#define %s_LAYOUT_H\n", p, p);
  printf("#define %s_LDX %uu\n", p, (unsigned)QWEN_LDX);
  printf("#define %s_REPLICAS %uu\n", p, (unsigned)QWEN_X_REPLICAS);
  printf("#define %s_STRIDE_E %uu\n", p, (unsigned)QWEN_X_STRIDE_E);
  printf("#define %s_ELEMS %uu\n", p, (unsigned)QWEN_X_ELEMS);
  printf("#endif\n");
  return 0;
}
